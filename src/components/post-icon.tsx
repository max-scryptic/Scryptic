/*
 * The post's subject icon, large and faint in the corner of a post card, in
 * the place a tool's logo takes on a migration guide (see ToolLogoWatermark),
 * so cards with and without a logo read as one set. Place it inside a
 * positioned, isolated parent: it sits at -z-10, behind the content but above
 * the card's background. Decorative, since the card prints the topic. Renders
 * nothing for a post with a logo or without an icon.
 */
export function PostIconWatermark({ post }: { post: Pick<BlogPost, "logo" | "icon"> }) {
  if (post.logo || !post.icon) return null

  return (
    <div
      aria-hidden="true"
      className="pointer-events-none absolute inset-0 -z-10 overflow-hidden rounded-[inherit]"
    >
      <svg
        viewBox="0 0 24 24"
        fill="none"
        stroke="currentColor"
        strokeWidth="1.25"
        strokeLinecap="round"
        strokeLinejoin="round"
        className="absolute -right-8 -bottom-8 size-48 text-primary opacity-15 transition duration-300 group-hover:-translate-x-1 group-hover:-translate-y-1 group-hover:opacity-25 dark:opacity-25 dark:group-hover:opacity-35"
      >
        {paths[post.icon]}
      </svg>
    </div>
  )
}
